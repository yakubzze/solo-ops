const dictionaries: Record<Locale, Record<MessageKey, string>> = { en, pl }

export const LOCALES: { id: Locale; label: string }[] = [
  { id: 'en', label: 'English' },
  { id: 'pl', label: 'Polski' },
]

let current: Locale = 'en'
const listeners = new Set<() => void>()

/**
 * This module deliberately does not import the store. The store reads dates,
 * dates read messages, and a message that reached back into the store would close
 * a circle that only breaks at runtime, in whichever module happens to load first.
 */
export function setLocale(locale: Locale) {
  const next = dictionaries[locale] ? locale : 'en'
  if (next === current) return
  current = next
  for (const fn of listeners) fn()
}

export function getLocale(): Locale {
  return current
}

/** Module-level lookup, for code that runs outside a component. */
export function t(key: MessageKey, params?: Record<string, string | number>): string {
  const template = dictionaries[current][key] ?? en[key] ?? key
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (_m, name: string) => String(params[name] ?? `{${name}}`))
}

/**
 * The same lookup, subscribed — a component calling this re-renders when the
 * language changes, which a bare module-level call would not do.
 */
export function useT() {
  useSyncExternalStore(
    (onChange) => {
      listeners.add(onChange)
      return () => listeners.delete(onChange)
    },
    () => current,
    () => current
  )
  return t
}
